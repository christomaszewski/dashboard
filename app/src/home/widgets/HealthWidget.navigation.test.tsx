// @vitest-environment jsdom
import { cleanup, fireEvent, screen } from "@testing-library/react";
import { afterEach, describe, expect, it, vi } from "vitest";
import type { HealthWidgetConfig } from "../../config/schema";
import { diagnosticStatuses } from "../../health/diagnostics";
import { HealthDiscovery } from "../../health/discovery";
import type { HealthService, HealthValue } from "../../health/types";
import { buildGraph } from "../../ros/graph";
import { buildRos2StaticDecoder } from "../../schema/decoders/staticDefs";
import { health, renderWith } from "../../test/harness";
import { TransportCtx } from "../../transport/TransportContext";
import type { Transport } from "../../transport/types";
import { HealthWidget } from "./HealthWidget";
import fixtures from "../../health/sbg-fixtures.json";

// Unmodified CDR reports from sbg_driver v0.8.1, generated by
// src/sbg_driver/test/health_publisher_test.cpp (representative_reports).
// Source: https://github.com/christomaszewski/sbg_driver/blob/af9a6504bcfc078d859c758bf25c571ae09a82e4/src/sbg_driver/test/fixtures/health_diagnostics.json
const topic = buildGraph([
  "@ros2_lv/0/z/1/2/MP/%/%front/sbg_driver/%diagnostics/diagnostic_msgs::msg::dds_::DiagnosticArray_/hash/::,10::::",
]).topics[0];
const stores: HealthDiscovery[] = [];
afterEach(async () => {
  cleanup(); localStorage.clear();
  await Promise.all(stores.splice(0).map((store) => store.stop()));
});
const widget = (over: Partial<HealthWidgetConfig> = {}): HealthWidgetConfig => ({ type: "health", history_s: 0, precision: 1, ...over });
const navigation = () => [...document.querySelectorAll(".health-summary-navigation")];
const rows = () => navigation().map((r) => [r.querySelector(".health-metric-label")?.textContent, r.querySelector(".row-value")?.textContent]);
const show = (service: HealthService, over: Partial<HealthWidgetConfig> = {}) =>
  renderWith(<HealthWidget widget={widget(over)} />, { healths: [service] });
const current = { "health.sample_age_s": 0, "health.stale_after_s": 5, "health.availability": "current" };
const sbg = () => health("ins", {
  temperature: { values: { ...current, "temp.imu_c": 41.5 } },
  gnss: { values: { ...current, "gnss.fix_type": "RTK_INT", "gnss.sv_used": 21 } },
  ekf: { values: { ...current, "ekf.solution_mode": "NAV_POSITION" } },
  "gnss heading": { values: { ...current, "gnss.heading_valid": true } },
});

async function ingest(...reports: (keyof typeof fixtures)[]) {
  const decoder = await buildRos2StaticDecoder("diagnostic_msgs/msg/DiagnosticArray");
  const transport = { liveliness: { subscribe: vi.fn(async () => ({ close() {} })) },
    subscribe: vi.fn(async () => ({ close() {} })) } as unknown as Transport;
  const store = new HealthDiscovery(transport);
  stores.push(store);
  let services: HealthService[] = [];
  await store.start((next) => { services = next; });
  for (const report of reports) {
    store.ingestRos(topic, decoder.decode(Uint8Array.from(atob(fixtures[report]), (c) => c.charCodeAt(0))));
    expect(decoder.lastWarning?.()).toBeUndefined();
  }
  expect(services).toHaveLength(1);
  return services[0];
}

describe("navigation in the health widget", () => {
  it.each(["native", "ros2"])("shows healthy navigation alongside temperature from %s values", (source) => {
    const service = sbg();
    if (source === "ros2") service.snapshot.status = diagnosticStatuses({ status: service.snapshot.status.map((s) => ({
      ...s, values: Object.entries(s.values).map(([key, value]) => ({ key, value: String(value) })),
    })) });
    show(service);
    expect(rows()).toEqual([["GNSS", "RTK fixed"], ["satellites", "21"], ["EKF", "Nav position"], ["heading", "Valid"]]);
    expect(screen.getByRole("button", { name: "imu temperature: 41.5 °C" })).toBeTruthy();
    expect(navigation().every((n) => n.classList.contains("ok"))).toBe(true);
    expect(document.querySelector(".health-issue")).toBeNull();
    fireEvent.focus(screen.getByRole("button", { name: "GNSS: RTK fixed" }));
    expect(screen.getByRole("tooltip").textContent).toContain("gnss.fix_typeRTK_INT");
    expect(screen.getByRole("tooltip").textContent).toContain("current · sample 0s old");
  });

  it("decodes actual SBG CDR through discovery and qualified selection without hiding its fault", async () => {
    const service = await ingest("active");
    show(service, { services: ["uav6/ins"] });
    expect(service.key).toBe("fleet/uav6/svc/ins/health");
    expect(rows()).toEqual([["GNSS", "RTK fixed"], ["satellites", "21"], ["EKF", "Nav position"], ["heading", "Valid"]]);
    expect(screen.getByRole("button", { name: "ERROR MAIN_POWER" })).toBeTruthy();
    expect(screen.getByRole("button", { name: "imu temperature: 41.5 °C" })).toBeTruthy();
    fireEvent.click(screen.getByRole("button", { name: "heading: Valid" }));
    expect(screen.getByRole("tooltip").textContent).toContain("QUANTA-USG 000123");
    expect(screen.getByRole("tooltip").textContent).toContain("gnss.heading_accuracy_deg0.18");
  });

  it("keeps serialized cached values and faults stale, then drops old inventory on restart", async () => {
    show(await ingest("active", "silent"));
    expect(rows()).toEqual([["GNSS", "RTK fixed"], ["satellites", "21"], ["EKF", "Nav position"], ["heading", "Valid"]]);
    expect(navigation().every((n) => n.classList.contains("idle") && n.textContent?.includes("last known"))).toBe(true);
    expect(screen.getByRole("button", { name: "ERROR MAIN_POWER" })).toBeTruthy();
    expect(screen.getByRole("button", { name: "WARN gnss" })).toBeTruthy(); // producer reports a collection error too
    cleanup();
    show(await ingest("active", "restart", "silent")); // old publisher cannot resurrect heading/faults
    expect(rows()).toEqual([["GNSS", "RTK float"], ["satellites", "21"], ["EKF", "AHRS"]]);
    expect(screen.queryByRole("button", { name: /heading:/ })).toBeNull();
    expect(screen.queryByRole("button", { name: "ERROR MAIN_POWER" })).toBeNull();
    expect(screen.getByRole("button", { name: "WARN gnss" })).toBeTruthy();
    expect(screen.getByRole("button", { name: "WARN ekf" })).toBeTruthy();
  });

  it.each([false, "false"])("shows invalid heading for %s without treating it as truthy", (value) => {
    show(health("ins", { "gnss heading": { level: 1, values: { ...current, "gnss.heading_valid": value } } }));
    expect(rows()).toEqual([["heading", "Invalid"]]);
    expect(navigation()[0].classList.contains("warn")).toBe(true);
    expect(screen.getByRole("button", { name: "WARN gnss heading" })).toBeTruthy();
  });

  it("preserves no-fix warnings, EKF errors and genuine zero satellites", () => {
    show(health("ins", {
      gnss: { level: 1, values: { "gnss.fix_type": "NO_SOLUTION", "gnss.sv_used": "0" } },
      ekf: { level: 2, values: { "ekf.solution_mode": "UNINITIALIZED" } },
    }));
    expect(rows()).toEqual([["GNSS", "No fix"], ["satellites", "0"], ["EKF", "Uninitialized"]]);
    expect(navigation().map((n) => n.querySelector(".row-value")?.className)).toEqual(["row-value warn", "row-value warn", "row-value err"]);
    expect(screen.getByRole("button", { name: "WARN gnss" })).toBeTruthy();
    expect(screen.getByRole("button", { name: "ERROR ekf" })).toBeTruthy();
  });

  it("does not infer a warning from fix grade or apply temperature thresholds to navigation", () => {
    show(health("ins", { gnss: { values: { "gnss.fix_type": "SINGLE", "gnss.sv_used": 0 } } }), { warn_above: 0, err_above: 1 });
    expect(rows()).toEqual([["GNSS", "Single"], ["satellites", "0"]]);
    expect(navigation().every((n) => n.classList.contains("ok"))).toBe(true);
    expect(document.querySelector(".health-issue")).toBeNull();
  });

  it("expires GNSS independently while fresh EKF and temperature remain current", () => {
    const service = sbg();
    service.snapshot.status[1].values["health.sample_age_s"] = 10;
    show(service);
    expect(navigation().map((n) => n.classList.contains("idle"))).toEqual([true, true, false, false]);
    expect(screen.getByRole("button", { name: "imu temperature: 41.5 °C" }).classList.contains("ok")).toBe(true);
    expect(screen.getByRole("button", { name: "STALE gnss" })).toBeTruthy();
    fireEvent.focus(screen.getByRole("button", { name: "GNSS: RTK fixed, last known" }));
    expect(screen.getByRole("tooltip").textContent).toContain("Stale · last known · sample 10s old");
  });

  it.each(["offline", "silent", "disconnected", "paused"])("dims navigation when %s without losing the last error", (reason) => {
    const service = sbg();
    service.snapshot.status[2].level = 3;
    service.snapshot.status[2].values["health.last_level"] = 2;
    for (const s of service.snapshot.status) s.values["health.stale_after_s"] = 60;
    if (reason === "offline") service.alive = false;
    if (reason === "silent") service.receivedAtMs -= 10_000;
    if (reason === "paused") for (const s of service.snapshot.status) s.values["health.availability"] = "paused";
    renderWith(<TransportCtx.Provider value={{ transport: null, status: reason === "disconnected" ? "reconnecting" : "connected", error: "", locator: "test" }}>
      <HealthWidget widget={widget()} /></TransportCtx.Provider>, { healths: [service] });
    expect(navigation().every((n) => n.classList.contains("idle") && n.textContent?.includes("last known"))).toBe(true);
    expect(screen.getByRole("button", { name: "ERROR ekf" }).classList.contains("err")).toBe(true);
  });

  it.each([null, "", " ", "NaN", "Infinity", true, false, -1, 1.5, "-1", "1.5", "21 satellites"] as HealthValue[])
    ("never turns an invalid satellite count %s into a number", (value) => {
      show(health("ins", { gnss: { values: { "gnss.sv_used": value } } }));
      expect(rows()).toEqual([["satellites", "—"]]);
      expect(navigation()[0].textContent).toContain("unavailable");
      expect(navigation()[0].classList.contains("idle")).toBe(true);
    });

  it("shows unavailable text/boolean values, omits absent and unsupported fields, and preserves unknown modes", () => {
    show(health("ins", {
      gnss: { values: { "gnss.fix_type": null, "gnss.sv_used": 21, "health.metric.gnss.sv_used.state": "unsupported" } },
      ekf: { values: { "ekf.solution_mode": "MODE_7" } },
      "gnss heading": { values: { "gnss.heading_valid": "unknown" } },
    }));
    expect(rows()).toEqual([["GNSS", "—"], ["EKF", "MODE_7"], ["heading", "—"]]);
    cleanup();
    show(health("ins", { gnss: {}, ekf: { values: { "ekf.solution_mode": 4 } } }));
    expect(rows()).toEqual([["EKF", "—"]]);
  });

  it("marks individual unavailable values last known without suppressing another field", () => {
    const service = sbg();
    service.snapshot.status[1].values["health.metric.gnss.sv_used.state"] = "unavailable";
    show(service);
    expect(screen.getByRole("button", { name: "satellites: 21, last known" }).classList.contains("idle")).toBe(true);
    expect(screen.getByRole("button", { name: "GNSS: RTK fixed" }).classList.contains("ok")).toBe(true);
    expect(screen.getByRole("button", { name: "WARN gnss" })).toBeTruthy();
  });

  it("respects component filters and renders the same indicators in compact panels", () => {
    renderWith(<HealthWidget widget={widget({ components: ["gnss"] })} compact />, { healths: [sbg()] });
    expect(rows()).toEqual([["GNSS", "RTK fixed"], ["satellites", "21"]]);
    expect(document.querySelector(".widget-card")).toBeNull();
    expect(screen.queryByRole("button", { name: /imu temperature/ })).toBeNull();
  });
});
